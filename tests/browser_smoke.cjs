const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true, ...(process.env.BROWSER_EXECUTABLE ? {executablePath:process.env.BROWSER_EXECUTABLE} : {})});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const base=process.env.BROWSER_SMOKE_BASE;
 if(!base) throw new Error('BROWSER_SMOKE_BASE must point to a fresh isolated test server');
 const uploaded=await page.request.post(base+'/api/sources/upload',{multipart:{file:{name:'收尾验收.md',mimeType:'text/markdown',buffer:Buffer.from('# 收尾验收\n\nAthena 服务支持 52000 QPS。每周整理知识并核对原文。')}}});assert.equal(uploaded.status(),200);
 await page.goto(base+'/#wiki');
 await page.getByRole('heading',{name:'知识页面',exact:true}).waitFor();
 await page.locator('#wiki-directory [data-wiki-page]').filter({hasText:'收尾验收.md'}).click();
 await page.locator('#wiki-edit').waitFor({state:'attached'});
 await page.getByText('修订正文（先进入审核队列）',{exact:true}).click();
 await page.locator('#wiki-edit textarea').fill('# 收尾验收\n\n已审核的人工正文。');
 await page.getByRole('button',{name:'生成待审差异',exact:true}).click();
 await page.locator('.wiki-op > summary').click();
 await page.getByRole('button',{name:'批准发布',exact:true}).click();
 await page.locator('#wiki-directory [data-wiki-page]').filter({hasText:'收尾验收.md'}).click();
 await page.locator('.wiki-body').first().filter({hasText:'已审核的人工正文'}).waitFor();
 await page.getByText('正文历史与回滚',{exact:true}).click();
 page.once('dialog',d=>d.accept());
 await page.locator('[data-wiki-rev="1"]').click();
 await page.locator('.wiki-body').first().filter({hasText:'52000'}).waitFor();
 await page.getByText('原文证据（1）',{exact:true}).click();
 await page.locator('[data-wiki-source]').first().click();
 await page.locator('#view-title').filter({hasText:'资料库'}).waitFor();
 assert(await page.locator('#view').innerText().then(t=>t.includes('收尾验收.md')));
 await page.locator('#nav [data-nav="wiki"]').click();
 await page.locator('#wiki-compose input[name="title"]').fill('验收提纲');
 await page.locator('#wiki-compose input[name="slug"]').first().check();
 await page.getByRole('button',{name:'预览材料',exact:true}).click();
 await page.locator('#wiki-compose-result').filter({hasText:'52000'}).waitFor();
 await page.getByRole('button',{name:'提交到待审队列',exact:true}).click();
 await page.locator('.wiki-op summary').filter({hasText:'验收提纲'}).waitFor();
 await page.locator('#wiki-auto').uncheck();
 await page.waitForFunction(()=>!document.querySelector('#wiki-auto').disabled);
 assert.equal((await (await page.request.get(base+'/api/wiki/settings')).json()).auto_apply,false);
 await page.setViewportSize({width:390,height:844});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile overflow');
 assert.deepEqual(errors,[]);
 console.log('PASS: browse, edit, review, rollback, source, compose, settings, mobile; no browser errors');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
